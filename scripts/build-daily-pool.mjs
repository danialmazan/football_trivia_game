import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const players = JSON.parse(readFileSync(new URL('../src/data/players.json', import.meta.url), 'utf8'))
const normalPlayers = players
  .filter((player) => player.normalPool)
  .sort(
    (a, b) =>
      b.recognitionScore - a.recognitionScore ||
      a.displayName.localeCompare(b.displayName),
  )

const rosterVersion = createHash('sha256')
  .update(normalPlayers.map((player) => player.id).join('\n'))
  .digest('hex')
  .slice(0, 16)

const values = normalPlayers
  .map(
    (player, index) =>
      `  ('${player.id.replaceAll("'", "''")}', '${rosterVersion}', ${index + 1}, true)`,
  )
  .join(',\n')

const sql = `-- Generated by scripts/build-daily-pool.mjs. Do not edit by hand.
insert into public.daily_player_pool (player_id, roster_version, ranking, active)
values
${values}
on conflict (player_id) do update set
  roster_version = excluded.roster_version,
  ranking = excluded.ranking,
  active = excluded.active;

update public.daily_player_pool
set active = false
where roster_version <> '${rosterVersion}';
`

writeFileSync(
  new URL('../supabase/migrations/202607290002_daily_player_pool.sql', import.meta.url),
  sql,
)

console.log(`Wrote ${normalPlayers.length} daily players for roster ${rosterVersion}.`)
